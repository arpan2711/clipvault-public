// Builds src/renderer/icons.svg, the app's one icon sprite, from the vendored Lucide icons in
// assets/icons/lucide/. Run after adding or removing an icon: node scripts/build-icons.js
// Every shape gets vector-effect="non-scaling-stroke", so strokes stay 1.5 px at any icon size:
// page CSS can't reach shapes cloned from an external sprite by <use>.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'assets', 'icons', 'lucide');
const OUT = path.join(__dirname, '..', 'src', 'renderer', 'icons.svg');
const SHAPE = /<(path|line|polyline|polygon|circle|rect|ellipse)\b/g;

const symbols = fs.readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort().map((f) => {
  const raw = fs.readFileSync(path.join(SRC, f), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '').replace(SHAPE, '<$1 vector-effect="non-scaling-stroke"');
  return `<symbol id="i-${f.replace(/\.svg$/, '')}" viewBox="0 0 24 24">${inner}</symbol>`;
});
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons (ISC, see assets/icons/lucide/LICENSE). Generated by scripts/build-icons.js: don't edit. -->\n${symbols.join('\n')}\n</svg>\n`;
fs.writeFileSync(OUT, sprite);
console.log(`wrote ${path.relative(path.join(__dirname, '..'), OUT)} with ${symbols.length} icons`);
